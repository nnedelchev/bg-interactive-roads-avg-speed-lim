const ROAD_COLORS = {
    highways: ['#2929b9ff'],
    mainRoads: ['#2980b9'],
    secondaryRoads: ['#3498db', '#2980b9', '#1abc9c']
};

const SPEED_LIMITS = {
    HIGHWAY: 130,
    MAIN_ROAD: 90,
    SECONDARY_ROAD: 50,
    CITY_ROAD: 50,
    RESIDENTIAL: 30
};

const RoadDataUtils = {
    getRoadsByType: function (type) {
        return ROAD_TRACKS[type] || [];
    },

    getRoadById: function (id) {
        for (const roadType of Object.values(ROAD_TRACKS)) {
            const road = roadType.find(r => r.id === id);
            if (road) return road;
        }
        return null;
    },

    getRoadColor: function (type, index = 0) {
        const colors = ROAD_COLORS[type];
        return colors ? colors[index % colors.length] : '#333333';
    },

    hasCoordinates: function(road) {
        return road.coordinates && road.coordinates.length > 0;
    },

    getFallbackCoordinates: function(road) {
        return [road.startPoint.coordinates, road.endPoint.coordinates];
    }
};

