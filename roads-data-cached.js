// Road colors configuration
const ROAD_COLORS = {
    highways: ['#2929b9ff'], // Red, Dark Red, Purple, Blue
    mainRoads: ['#2980b9'], // Orange, Dark Orange, Darker Orange
    secondaryRoads: ['#3498db', '#2980b9', '#1abc9c'] // Blue, Dark Blue, Teal
};


// Speed limit categories
const SPEED_LIMITS = {
    HIGHWAY: 130,
    MAIN_ROAD: 90,
    SECONDARY_ROAD: 50,
    CITY_ROAD: 50,
    RESIDENTIAL: 30
};

// Utility functions for road data
const RoadDataUtils = {
    // Get all roads of a specific type
    getRoadsByType: function (type) {
        return ROAD_TRACKS[type] || [];
    },

    // Get road by ID
    getRoadById: function (id) {
        for (const roadType of Object.values(ROAD_TRACKS)) {
            const road = roadType.find(r => r.id === id);
            if (road) return road;
        }
        return null;
    },

    // Get color for road by type and index
    getRoadColor: function (type, index = 0) {
        const colors = ROAD_COLORS[type];
        return colors ? colors[index % colors.length] : '#333333';
    },

    // Add a new road track
    addRoadTrack: function (type, roadData) {
        if (!ROAD_TRACKS[type]) {
            ROAD_TRACKS[type] = [];
        }
        ROAD_TRACKS[type].push(roadData);
    },

    // Validate road data structure
    validateRoadData: function (roadData) {
        const required = ['id', 'name', 'startPoint', 'endPoint', 'speedLimit'];
        const hasRequired = required.every(field => roadData.hasOwnProperty(field));

        if (!hasRequired) return false;

        const hasValidPoints = roadData.startPoint.name &&
            roadData.startPoint.coordinates &&
            roadData.endPoint.name &&
            roadData.endPoint.coordinates;

        return hasValidPoints;
    }
};

